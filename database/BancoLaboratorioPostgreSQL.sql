CREATE FUNCTION movimentar_estoque(p_chefe bigint,p_item bigint,p_variacao numeric,p_motivo text) RETURNS numeric
LANGUAGE plpgsql SET search_path = gestao_lab, public AS $$
DECLARE v_lab bigint; v_qtd numeric;
BEGIN
    SELECT laboratorio_id INTO STRICT v_lab FROM item_estoque WHERE id=p_item;
    PERFORM exigir_chefe(p_chefe,v_lab);
    PERFORM contexto_operacao(p_chefe,p_motivo);
    IF p_variacao=0 OR p_variacao IS NULL THEN RAISE EXCEPTION 'Variação deve ser diferente de zero' USING ERRCODE='23514'; END IF;
    UPDATE item_estoque SET quantidade=quantidade+p_variacao WHERE id=p_item RETURNING quantidade INTO v_qtd;
    RETURN v_qtd;
END $$;
CREATE FUNCTION avaliar_alertas_estoque(p_laboratorio bigint DEFAULT NULL) RETURNS integer
LANGUAGE plpgsql SET search_path = gestao_lab, public AS $$
DECLARE v record; v_chave text; v_id bigint; v_total integer:=0;
BEGIN
    -- Executar periodicamente no serviço de tarefas; o banco não agenda SMTP.
    FOR v IN SELECT i.*,l.chefe_usuario_id,l.dias_alerta_validade FROM item_estoque i
             JOIN laboratorio l ON l.id=i.laboratorio_id WHERE i.ativo AND l.ativo
             AND (p_laboratorio IS NULL OR i.laboratorio_id=p_laboratorio) LOOP
        v_chave:='estoque_baixo:'||v.id;
        IF v.quantidade<=v.limite_estoque_baixo THEN
            v_id:=notificar(v.laboratorio_id,v.chefe_usuario_id,'ESTOQUE_BAIXO','Estoque baixo: '||v.nome,
                            jsonb_build_object('item_id',v.id,'quantidade',v.quantidade),v_chave);
            IF v_id IS NOT NULL THEN v_total:=v_total+1; END IF;
        ELSE UPDATE notificacao SET chave_deduplicacao=NULL WHERE destinatario_id=v.chefe_usuario_id AND chave_deduplicacao=v_chave;
        END IF;
        v_chave:='validade:'||v.id;
        IF v.validade IS NOT NULL AND v.validade<=current_date+v.dias_alerta_validade THEN
            v_id:=notificar(v.laboratorio_id,v.chefe_usuario_id,'VALIDADE','Validade próxima ou vencida: '||v.nome,
                            jsonb_build_object('item_id',v.id,'validade',v.validade),v_chave);
            IF v_id IS NOT NULL THEN v_total:=v_total+1; END IF;
        ELSE UPDATE notificacao SET chave_deduplicacao=NULL WHERE destinatario_id=v.chefe_usuario_id AND chave_deduplicacao=v_chave;
        END IF;
    END LOOP;
    RETURN v_total;
END $$;
CREATE FUNCTION tg_notificar_ocorrencia() RETURNS trigger
LANGUAGE plpgsql SET search_path = gestao_lab, public AS $$
DECLARE v_chefe bigint;
BEGIN
    SELECT chefe_usuario_id INTO v_chefe FROM laboratorio WHERE id=NEW.laboratorio_id;
    PERFORM notificar(NEW.laboratorio_id,v_chefe,'OCORRENCIA',NEW.descricao,jsonb_build_object('ocorrencia_id',NEW.id));
    RETURN NEW;
END $$;
