-- Auditoria automática, sem credenciais ou conteúdo binário nos snapshots.
CREATE FUNCTION tg_auditar() RETURNS trigger
LANGUAGE plpgsql SET search_path = gestao_lab, public AS $$
DECLARE v_antes jsonb; v_depois jsonb; v_row jsonb; v_lab bigint; v_ator bigint; v_id text;
BEGIN
    v_antes:=CASE WHEN TG_OP<>'INSERT' THEN to_jsonb(OLD)-ARRAY['senha_hash','pdf_original','token_hash'] END;
    v_depois:=CASE WHEN TG_OP<>'DELETE' THEN to_jsonb(NEW)-ARRAY['senha_hash','pdf_original','token_hash'] END;
    v_row:=coalesce(v_depois,v_antes);
    v_lab:=CASE WHEN TG_TABLE_NAME='laboratorio' THEN (v_row->>'id')::bigint ELSE (v_row->>'laboratorio_id')::bigint END;
    v_ator:=nullif(current_setting('app.usuario_id',true),'')::bigint;
    -- Migração/bootstrap sem ator e atuação do sistema são explicitamente NULL.
    IF NOT EXISTS(SELECT 1 FROM usuario WHERE id=v_ator AND laboratorio_id=v_lab) THEN v_ator:=NULL; END IF;
    v_id:=coalesce(v_row->>'id',v_row->>'recurso_id',v_row->>'usuario_id',v_row->>'protocolo_id');
    IF TG_TABLE_NAME='reserva_recurso' THEN v_id:=(v_row->>'reserva_id')||':'||(v_row->>'recurso_id'); END IF;
    IF TG_TABLE_NAME='protocolo_equipamento' THEN v_id:=(v_row->>'protocolo_id')||':'||(v_row->>'equipamento_id'); END IF;
    INSERT INTO historico_uso(laboratorio_id,ator_id,tabela,registro_id,acao,motivo,antes,depois)
    VALUES(v_lab,v_ator,TG_TABLE_NAME,v_id,TG_OP,nullif(current_setting('app.motivo',true),''),v_antes,v_depois);
    RETURN coalesce(NEW,OLD);
END $$;
CREATE FUNCTION tg_impedir_exclusao() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    RAISE EXCEPTION 'Exclusão física de % bloqueada para preservar histórico; use desativação ou encerramento',TG_TABLE_NAME USING ERRCODE='23514';
END $$;
CREATE FUNCTION tg_historico_imutavel() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    RAISE EXCEPTION 'Histórico é imutável' USING ERRCODE='23514';
END $$;
DO $$
DECLARE v_tabela text;
BEGIN
    FOREACH v_tabela IN ARRAY ARRAY['laboratorio','usuario','aluno','professor','chefe_laboratorio','recurso','sala','bancada','equipamento',
        'reserva','reserva_recurso','chave','emprestimo_chave','ocorrencia_chave','item_estoque','movimentacao_estoque',
        'protocolo','protocolo_equipamento','proibicao_aluno_equipamento','solicitacao_reativacao','ocorrencia'] LOOP
        EXECUTE format('CREATE TRIGGER auditar AFTER INSERT OR UPDATE OR DELETE ON %I FOR EACH ROW EXECUTE FUNCTION tg_auditar()',v_tabela);
        EXECUTE format('CREATE TRIGGER impedir_exclusao BEFORE DELETE ON %I FOR EACH ROW EXECUTE FUNCTION tg_impedir_exclusao()',v_tabela);
        EXECUTE format('CREATE TRIGGER impedir_truncate BEFORE TRUNCATE ON %I FOR EACH STATEMENT EXECUTE FUNCTION tg_impedir_exclusao()',v_tabela);
    END LOOP;
END $$;
CREATE TRIGGER historico_imutavel BEFORE UPDATE OR DELETE ON historico_uso FOR EACH ROW EXECUTE FUNCTION tg_historico_imutavel();
