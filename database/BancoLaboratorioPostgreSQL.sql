CREATE FUNCTION tg_usuario_subtipo() RETURNS trigger
LANGUAGE plpgsql SET search_path = gestao_lab, public AS $$
DECLARE v_id bigint; v_total integer;
BEGIN
    v_id := CASE WHEN TG_TABLE_NAME='usuario' THEN coalesce((to_jsonb(NEW)->>'id')::bigint,(to_jsonb(OLD)->>'id')::bigint)
                 ELSE coalesce((to_jsonb(NEW)->>'usuario_id')::bigint,(to_jsonb(OLD)->>'usuario_id')::bigint) END;
    IF EXISTS (SELECT 1 FROM usuario WHERE id=v_id) THEN
        SELECT (EXISTS(SELECT 1 FROM aluno WHERE usuario_id=v_id))::integer
             + (EXISTS(SELECT 1 FROM professor WHERE usuario_id=v_id))::integer INTO v_total;
        IF v_total<>1 THEN RAISE EXCEPTION 'Usuário % exige exatamente um subtipo: Aluno ou Professor',v_id USING ERRCODE='23514'; END IF;
    END IF;
    RETURN NULL;
END $$;
