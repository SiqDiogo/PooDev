-- Instalação completa: conectar ao banco gestao_laboratorio e executar.
-- Não inclui dados fictícios. Conteúdo: 01_schema.sql + 02_regras.sql.

-- Sistema de Gestão de Laboratório de Pesquisa — PostgreSQL 16 ou superior.
-- Executar uma única vez em banco vazio. Não apaga nem substitui dados existentes.
-- As regras e funções complementares estão em 02_regras.sql.
BEGIN;
CREATE EXTENSION IF NOT EXISTS btree_gist WITH SCHEMA public;
CREATE SCHEMA gestao_lab;
SET LOCAL search_path = gestao_lab, public;
SET LOCAL TIME ZONE 'America/Sao_Paulo';

CREATE TYPE tipo_recurso AS ENUM ('SALA', 'BANCADA', 'EQUIPAMENTO');
CREATE TYPE estado_recurso AS ENUM ('DISPONIVEL', 'MANUTENCAO', 'DANIFICADO', 'DESATIVADO');
CREATE TYPE tipo_aluno AS ENUM ('GRADUACAO', 'MESTRADO', 'DOUTORADO', 'POS');
CREATE TYPE estado_reserva AS ENUM ('CONFIRMADA', 'CANCELADA', 'CONCLUIDA');
-- EM_USO é derivado de empréstimo aberto, nunca um estado manual da cópia.
CREATE TYPE condicao_chave AS ENUM ('OPERACIONAL', 'EXTRAVIADA', 'INDISPONIVEL');
CREATE TYPE estado_solicitacao AS ENUM ('PENDENTE', 'APROVADA', 'NEGADA');
CREATE TYPE estado_protocolo AS ENUM ('NAO_VALIDADO', 'VALIDADO');
CREATE TYPE estado_envio AS ENUM ('PENDENTE', 'ENVIADO', 'FALHOU');

CREATE TABLE laboratorio (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome text NOT NULL CHECK (btrim(nome) <> ''),
    localizacao text NOT NULL CHECK (btrim(localizacao) <> ''),
    chefe_usuario_id bigint NOT NULL,
    -- NULL significa limite ainda não configurado; não se inventa valor padrão.
    duracao_maxima_reserva interval CHECK (duracao_maxima_reserva > interval '0' AND isfinite(duracao_maxima_reserva)),
    max_reservas_simultaneas integer CHECK (max_reservas_simultaneas > 0),
    dias_alerta_validade integer NOT NULL DEFAULT 30 CHECK (dias_alerta_validade >= 0),
    ativo boolean NOT NULL DEFAULT true,
    criado_em timestamptz NOT NULL DEFAULT clock_timestamp()
);

CREATE TABLE usuario (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    laboratorio_id bigint NOT NULL REFERENCES laboratorio(id) DEFERRABLE INITIALLY DEFERRED,
    nome text NOT NULL CHECK (btrim(nome) <> ''),
    email text NOT NULL UNIQUE CHECK (email = lower(btrim(email)) AND email ~ '^[^[:space:]@]+@[^[:space:]@]+\.[^[:space:]@]+$'),
    senha_hash text NOT NULL CHECK (length(senha_hash) >= 40),
    ativo boolean NOT NULL DEFAULT true,
    criado_em timestamptz NOT NULL DEFAULT clock_timestamp(),
    UNIQUE (id, laboratorio_id)
);
CREATE TABLE professor (
    usuario_id bigint PRIMARY KEY,
    laboratorio_id bigint NOT NULL,
    programa_pos text NOT NULL CHECK (btrim(programa_pos) <> ''),
    ramal text,
    UNIQUE (usuario_id, laboratorio_id),
    FOREIGN KEY (usuario_id, laboratorio_id) REFERENCES usuario(id, laboratorio_id) DEFERRABLE INITIALLY DEFERRED
);
CREATE TABLE aluno (
    usuario_id bigint PRIMARY KEY,
    laboratorio_id bigint NOT NULL,
    matricula text NOT NULL UNIQUE CHECK (btrim(matricula) <> ''),
    tipo tipo_aluno NOT NULL,
    orientador_usuario_id bigint NOT NULL,
    UNIQUE (usuario_id, laboratorio_id),
    FOREIGN KEY (usuario_id, laboratorio_id) REFERENCES usuario(id, laboratorio_id) DEFERRABLE INITIALLY DEFERRED,
    FOREIGN KEY (orientador_usuario_id, laboratorio_id) REFERENCES professor(usuario_id, laboratorio_id) DEFERRABLE INITIALLY DEFERRED
);
CREATE TABLE chefe_laboratorio (
    usuario_id bigint PRIMARY KEY,
    laboratorio_id bigint NOT NULL UNIQUE,
    UNIQUE (usuario_id, laboratorio_id),
    FOREIGN KEY (usuario_id, laboratorio_id) REFERENCES professor(usuario_id, laboratorio_id) DEFERRABLE INITIALLY DEFERRED
);
ALTER TABLE laboratorio ADD CONSTRAINT laboratorio_chefe_fk
    FOREIGN KEY (chefe_usuario_id, id) REFERENCES chefe_laboratorio(usuario_id, laboratorio_id) DEFERRABLE INITIALLY DEFERRED;

CREATE TABLE sessao_usuario (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id bigint NOT NULL REFERENCES usuario(id),
    token_hash bytea NOT NULL UNIQUE CHECK (octet_length(token_hash) = 32),
    criado_em timestamptz NOT NULL DEFAULT clock_timestamp(),
    expira_em timestamptz NOT NULL,
    revogado_em timestamptz,
    CHECK (expira_em > criado_em),
    CHECK (revogado_em IS NULL OR revogado_em >= criado_em)
);

CREATE TABLE recurso (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    laboratorio_id bigint NOT NULL REFERENCES laboratorio(id),
    tipo tipo_recurso NOT NULL,
    nome text NOT NULL CHECK (btrim(nome) <> ''),
    estado estado_recurso NOT NULL DEFAULT 'DISPONIVEL',
    responsavel_usuario_id bigint NOT NULL,
    observacao text,
    criado_em timestamptz NOT NULL DEFAULT clock_timestamp(),
    UNIQUE (id, laboratorio_id),
    UNIQUE (id, tipo),
    FOREIGN KEY (responsavel_usuario_id, laboratorio_id) REFERENCES professor(usuario_id, laboratorio_id)
);
CREATE TABLE sala (
    recurso_id bigint PRIMARY KEY,
    laboratorio_id bigint NOT NULL,
    tipo tipo_recurso GENERATED ALWAYS AS ('SALA'::tipo_recurso) STORED,
    identificacao text NOT NULL CHECK (btrim(identificacao) <> ''),
    localizacao text NOT NULL CHECK (btrim(localizacao) <> ''),
    capacidade integer NOT NULL CHECK (capacidade > 0),
    UNIQUE (recurso_id, laboratorio_id),
    UNIQUE (laboratorio_id, identificacao),
    FOREIGN KEY (recurso_id, laboratorio_id) REFERENCES recurso(id, laboratorio_id),
    FOREIGN KEY (recurso_id, tipo) REFERENCES recurso(id, tipo)
);
CREATE TABLE bancada (
    recurso_id bigint PRIMARY KEY,
    laboratorio_id bigint NOT NULL,
    tipo tipo_recurso GENERATED ALWAYS AS ('BANCADA'::tipo_recurso) STORED,
    sala_id bigint NOT NULL,
    numero_identificacao text NOT NULL CHECK (btrim(numero_identificacao) <> ''),
    UNIQUE (recurso_id, laboratorio_id),
    UNIQUE (sala_id, numero_identificacao),
    FOREIGN KEY (recurso_id, laboratorio_id) REFERENCES recurso(id, laboratorio_id),
    FOREIGN KEY (recurso_id, tipo) REFERENCES recurso(id, tipo),
    FOREIGN KEY (sala_id, laboratorio_id) REFERENCES sala(recurso_id, laboratorio_id)
);
CREATE TABLE equipamento (
    recurso_id bigint PRIMARY KEY,
    laboratorio_id bigint NOT NULL,
    tipo tipo_recurso GENERATED ALWAYS AS ('EQUIPAMENTO'::tipo_recurso) STORED,
    numero_patrimonio text NOT NULL UNIQUE CHECK (btrim(numero_patrimonio) <> ''),
    bancada_id bigint,
    sala_direta_id bigint,
    complemento_local text NOT NULL CHECK (btrim(complemento_local) <> ''),
    foto_uri text,
    UNIQUE (recurso_id, laboratorio_id),
    CHECK (num_nonnulls(bancada_id, sala_direta_id) = 1),
    FOREIGN KEY (recurso_id, laboratorio_id) REFERENCES recurso(id, laboratorio_id),
    FOREIGN KEY (recurso_id, tipo) REFERENCES recurso(id, tipo),
    FOREIGN KEY (bancada_id, laboratorio_id) REFERENCES bancada(recurso_id, laboratorio_id),
    FOREIGN KEY (sala_direta_id, laboratorio_id) REFERENCES sala(recurso_id, laboratorio_id)
);

CREATE TABLE reserva (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    laboratorio_id bigint NOT NULL REFERENCES laboratorio(id),
    usuario_id bigint NOT NULL,
    recurso_principal_id bigint NOT NULL,
    inicio timestamptz NOT NULL,
    fim timestamptz NOT NULL,
    periodo tstzrange GENERATED ALWAYS AS (tstzrange(inicio, fim, '[)')) STORED,
    estado estado_reserva NOT NULL DEFAULT 'CONFIRMADA',
    bloqueia boolean GENERATED ALWAYS AS (estado = 'CONFIRMADA') STORED,
    criado_em timestamptz NOT NULL DEFAULT clock_timestamp(),
    cancelado_em timestamptz,
    cancelado_por bigint,
    motivo_cancelamento text,
    UNIQUE (id, laboratorio_id),
    UNIQUE (id, periodo, bloqueia),
    CHECK (isfinite(inicio) AND isfinite(fim) AND fim > inicio),
    CHECK ((estado = 'CANCELADA' AND cancelado_em IS NOT NULL AND cancelado_por IS NOT NULL AND nullif(btrim(motivo_cancelamento), '') IS NOT NULL)
        OR (estado <> 'CANCELADA' AND cancelado_em IS NULL AND cancelado_por IS NULL AND motivo_cancelamento IS NULL)),
    FOREIGN KEY (usuario_id, laboratorio_id) REFERENCES usuario(id, laboratorio_id),
    FOREIGN KEY (recurso_principal_id, laboratorio_id) REFERENCES recurso(id, laboratorio_id),
    FOREIGN KEY (cancelado_por, laboratorio_id) REFERENCES usuario(id, laboratorio_id)
);
CREATE TABLE reserva_recurso (
    reserva_id bigint NOT NULL,
    recurso_id bigint NOT NULL,
    laboratorio_id bigint NOT NULL,
    periodo tstzrange NOT NULL,
    bloqueia boolean NOT NULL,
    -- Fotografia textual do local na confirmação; permanece após futuras mudanças.
    local_registrado jsonb NOT NULL,
    PRIMARY KEY (reserva_id, recurso_id),
    FOREIGN KEY (reserva_id, laboratorio_id) REFERENCES reserva(id, laboratorio_id),
    FOREIGN KEY (recurso_id, laboratorio_id) REFERENCES recurso(id, laboratorio_id),
    FOREIGN KEY (reserva_id, periodo, bloqueia) REFERENCES reserva(id, periodo, bloqueia) ON UPDATE CASCADE,
    CONSTRAINT reserva_recurso_sem_sobreposicao EXCLUDE USING gist
        (recurso_id WITH =, periodo WITH &&) WHERE (bloqueia)
);

CREATE TABLE chave (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    laboratorio_id bigint NOT NULL REFERENCES laboratorio(id),
    codigo_copia text NOT NULL UNIQUE CHECK (btrim(codigo_copia) <> ''),
    sala_id bigint,
    bancada_id bigint,
    condicao condicao_chave NOT NULL DEFAULT 'OPERACIONAL',
    designada_por bigint NOT NULL,
    -- NULL: cópia compartilhada. Preenchido: cópia designada a este usuário.
    designada_para bigint,
    criado_em timestamptz NOT NULL DEFAULT clock_timestamp(),
    UNIQUE (id, laboratorio_id),
    CHECK (num_nonnulls(sala_id, bancada_id) = 1),
    FOREIGN KEY (sala_id, laboratorio_id) REFERENCES sala(recurso_id, laboratorio_id),
    FOREIGN KEY (bancada_id, laboratorio_id) REFERENCES bancada(recurso_id, laboratorio_id),
    FOREIGN KEY (designada_por, laboratorio_id) REFERENCES professor(usuario_id, laboratorio_id),
    FOREIGN KEY (designada_para, laboratorio_id) REFERENCES usuario(id, laboratorio_id)
);
CREATE TABLE emprestimo_chave (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    laboratorio_id bigint NOT NULL REFERENCES laboratorio(id),
    chave_id bigint NOT NULL,
    usuario_id bigint NOT NULL,
    reserva_id bigint NOT NULL,
    retirada_em timestamptz NOT NULL DEFAULT clock_timestamp(),
    entregue_por bigint NOT NULL,
    devolucao_em timestamptz,
    recebido_por bigint,
    UNIQUE (id, laboratorio_id),
    CHECK ((devolucao_em IS NULL) = (recebido_por IS NULL)),
    CHECK (devolucao_em IS NULL OR devolucao_em >= retirada_em),
    FOREIGN KEY (chave_id, laboratorio_id) REFERENCES chave(id, laboratorio_id),
    FOREIGN KEY (usuario_id, laboratorio_id) REFERENCES usuario(id, laboratorio_id),
    FOREIGN KEY (reserva_id, laboratorio_id) REFERENCES reserva(id, laboratorio_id),
    FOREIGN KEY (entregue_por, laboratorio_id) REFERENCES professor(usuario_id, laboratorio_id),
    FOREIGN KEY (recebido_por, laboratorio_id) REFERENCES professor(usuario_id, laboratorio_id)
);
CREATE UNIQUE INDEX emprestimo_chave_uma_posse_aberta ON emprestimo_chave(chave_id) WHERE devolucao_em IS NULL;
CREATE TABLE ocorrencia_chave (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    laboratorio_id bigint NOT NULL REFERENCES laboratorio(id),
    chave_id bigint NOT NULL,
    registrado_por bigint NOT NULL,
    condicao condicao_chave NOT NULL,
    descricao text NOT NULL CHECK (btrim(descricao) <> ''),
    criado_em timestamptz NOT NULL DEFAULT clock_timestamp(),
    FOREIGN KEY (chave_id, laboratorio_id) REFERENCES chave(id, laboratorio_id),
    FOREIGN KEY (registrado_por, laboratorio_id) REFERENCES usuario(id, laboratorio_id)
);

CREATE TABLE item_estoque (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    laboratorio_id bigint NOT NULL REFERENCES laboratorio(id),
    nome text NOT NULL CHECK (btrim(nome) <> ''),
    lote text NOT NULL DEFAULT 'SEM_LOTE' CHECK (btrim(lote) <> ''),
    unidade text NOT NULL CHECK (btrim(unidade) <> ''),
    quantidade numeric(14,4) NOT NULL DEFAULT 0 CHECK (quantidade >= 0 AND quantidade <> 'NaN'::numeric),
    limite_estoque_baixo numeric(14,4) NOT NULL DEFAULT 0 CHECK (limite_estoque_baixo >= 0 AND limite_estoque_baixo <> 'NaN'::numeric),
    validade date,
    ativo boolean NOT NULL DEFAULT true,
    UNIQUE (id, laboratorio_id),
    UNIQUE (laboratorio_id, nome, lote)
);
CREATE TABLE movimentacao_estoque (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    laboratorio_id bigint NOT NULL REFERENCES laboratorio(id),
    item_id bigint NOT NULL,
    registrado_por bigint NOT NULL,
    variacao numeric(14,4) NOT NULL CHECK (variacao <> 0 AND variacao <> 'NaN'::numeric),
    quantidade_anterior numeric(14,4) NOT NULL CHECK (quantidade_anterior >= 0 AND quantidade_anterior <> 'NaN'::numeric),
    quantidade_posterior numeric(14,4) NOT NULL CHECK (quantidade_posterior >= 0 AND quantidade_posterior <> 'NaN'::numeric),
    motivo text NOT NULL CHECK (btrim(motivo) <> ''),
    criado_em timestamptz NOT NULL DEFAULT clock_timestamp(),
    CHECK (quantidade_posterior = quantidade_anterior + variacao),
    FOREIGN KEY (item_id, laboratorio_id) REFERENCES item_estoque(id, laboratorio_id),
    FOREIGN KEY (registrado_por, laboratorio_id) REFERENCES usuario(id, laboratorio_id)
);
CREATE TABLE protocolo (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    laboratorio_id bigint NOT NULL REFERENCES laboratorio(id),
    titulo text NOT NULL CHECK (btrim(titulo) <> ''),
    autor_id bigint NOT NULL,
    -- Arquivo original preservado no banco: exportação devolve estes mesmos bytes.
    pdf_original bytea NOT NULL CHECK (octet_length(pdf_original) > 5 AND substring(pdf_original FROM 1 FOR 5) = decode('255044462d', 'hex')),
    nome_arquivo text NOT NULL CHECK (lower(nome_arquivo) LIKE '%.pdf'),
    estado estado_protocolo NOT NULL DEFAULT 'NAO_VALIDADO',
    assinado_em timestamptz,
    assinado_por bigint,
    validado_em timestamptz,
    validado_por bigint,
    criado_em timestamptz NOT NULL DEFAULT clock_timestamp(),
    UNIQUE (id, laboratorio_id),
    CHECK ((assinado_em IS NULL) = (assinado_por IS NULL)),
    CHECK (assinado_por IS NULL OR assinado_por = autor_id),
    CHECK (assinado_em IS NULL OR assinado_em >= criado_em),
    CHECK ((estado = 'VALIDADO' AND validado_em IS NOT NULL AND validado_por IS NOT NULL)
        OR (estado = 'NAO_VALIDADO' AND validado_em IS NULL AND validado_por IS NULL)),
    CHECK (validado_em IS NULL OR (assinado_em IS NOT NULL AND validado_em >= assinado_em)),
    FOREIGN KEY (autor_id, laboratorio_id) REFERENCES usuario(id, laboratorio_id),
    FOREIGN KEY (assinado_por, laboratorio_id) REFERENCES usuario(id, laboratorio_id),
    FOREIGN KEY (validado_por, laboratorio_id) REFERENCES chefe_laboratorio(usuario_id, laboratorio_id)
);
CREATE TABLE protocolo_equipamento (
    protocolo_id bigint NOT NULL,
    equipamento_id bigint NOT NULL,
    laboratorio_id bigint NOT NULL,
    vinculado_por bigint NOT NULL,
    criado_em timestamptz NOT NULL DEFAULT clock_timestamp(),
    PRIMARY KEY (protocolo_id, equipamento_id),
    FOREIGN KEY (protocolo_id, laboratorio_id) REFERENCES protocolo(id, laboratorio_id),
    FOREIGN KEY (equipamento_id, laboratorio_id) REFERENCES equipamento(recurso_id, laboratorio_id),
    FOREIGN KEY (vinculado_por, laboratorio_id) REFERENCES chefe_laboratorio(usuario_id, laboratorio_id)
);

CREATE TABLE proibicao_aluno_equipamento (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    laboratorio_id bigint NOT NULL REFERENCES laboratorio(id),
    aluno_id bigint NOT NULL,
    equipamento_id bigint NOT NULL,
    motivo text NOT NULL CHECK (btrim(motivo) <> ''),
    aplicada_por bigint NOT NULL,
    criada_em timestamptz NOT NULL DEFAULT clock_timestamp(),
    encerrada_em timestamptz,
    encerrada_por bigint,
    UNIQUE (id, laboratorio_id),
    CHECK ((encerrada_em IS NULL) = (encerrada_por IS NULL)),
    CHECK (encerrada_em IS NULL OR encerrada_em >= criada_em),
    FOREIGN KEY (aluno_id, laboratorio_id) REFERENCES aluno(usuario_id, laboratorio_id),
    FOREIGN KEY (equipamento_id, laboratorio_id) REFERENCES equipamento(recurso_id, laboratorio_id),
    FOREIGN KEY (aplicada_por, laboratorio_id) REFERENCES chefe_laboratorio(usuario_id, laboratorio_id),
    FOREIGN KEY (encerrada_por, laboratorio_id) REFERENCES chefe_laboratorio(usuario_id, laboratorio_id)
);
CREATE UNIQUE INDEX proibicao_ativa_unica ON proibicao_aluno_equipamento(aluno_id, equipamento_id) WHERE encerrada_em IS NULL;
CREATE TABLE solicitacao_reativacao (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    laboratorio_id bigint NOT NULL REFERENCES laboratorio(id),
    proibicao_id bigint NOT NULL,
    solicitado_por bigint NOT NULL,
    justificativa text NOT NULL CHECK (btrim(justificativa) <> ''),
    estado estado_solicitacao NOT NULL DEFAULT 'PENDENTE',
    solicitada_em timestamptz NOT NULL DEFAULT clock_timestamp(),
    respondida_em timestamptz,
    respondida_por bigint,
    resposta text,
    CHECK ((estado <> 'PENDENTE' AND respondida_em IS NOT NULL AND respondida_por IS NOT NULL AND nullif(btrim(resposta), '') IS NOT NULL)
        OR (estado = 'PENDENTE' AND respondida_em IS NULL AND respondida_por IS NULL AND resposta IS NULL)),
    CHECK (respondida_em IS NULL OR respondida_em >= solicitada_em),
    FOREIGN KEY (proibicao_id, laboratorio_id) REFERENCES proibicao_aluno_equipamento(id, laboratorio_id),
    FOREIGN KEY (solicitado_por, laboratorio_id) REFERENCES aluno(usuario_id, laboratorio_id),
    FOREIGN KEY (respondida_por, laboratorio_id) REFERENCES chefe_laboratorio(usuario_id, laboratorio_id)
);
CREATE UNIQUE INDEX solicitacao_aberta_unica ON solicitacao_reativacao(proibicao_id) WHERE estado = 'PENDENTE';
CREATE TABLE ocorrencia (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    laboratorio_id bigint NOT NULL REFERENCES laboratorio(id),
    autor_id bigint NOT NULL,
    recurso_id bigint,
    item_estoque_id bigint,
    tipo text NOT NULL CHECK (tipo IN ('DANO', 'FALTA_ESTOQUE', 'OUTRO')),
    descricao text NOT NULL CHECK (btrim(descricao) <> ''),
    resolvida_em timestamptz,
    criado_em timestamptz NOT NULL DEFAULT clock_timestamp(),
    CHECK (num_nonnulls(recurso_id, item_estoque_id) <= 1),
    FOREIGN KEY (autor_id, laboratorio_id) REFERENCES usuario(id, laboratorio_id),
    FOREIGN KEY (recurso_id, laboratorio_id) REFERENCES recurso(id, laboratorio_id),
    FOREIGN KEY (item_estoque_id, laboratorio_id) REFERENCES item_estoque(id, laboratorio_id)
);

