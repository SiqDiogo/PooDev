CREATE FUNCTION notificar(p_lab bigint,p_destinatario bigint,p_tipo text,p_mensagem text,p_referencia jsonb DEFAULT '{}',p_dedup text DEFAULT NULL)
RETURNS bigint LANGUAGE plpgsql SET search_path = gestao_lab, public AS $$
DECLARE v_id bigint;
BEGIN
    INSERT INTO notificacao(laboratorio_id,destinatario_id,tipo,mensagem,referencia,chave_deduplicacao)
    VALUES(p_lab,p_destinatario,p_tipo,p_mensagem,p_referencia,p_dedup) ON CONFLICT DO NOTHING RETURNING id INTO v_id;
    IF v_id IS NOT NULL THEN INSERT INTO envio_email(notificacao_id) VALUES(v_id); END IF;
    RETURN v_id;
END $$;
CREATE FUNCTION criar_reserva(p_usuario bigint,p_recurso bigint,p_inicio timestamptz,p_fim timestamptz) RETURNS bigint
LANGUAGE plpgsql SET search_path = gestao_lab, public AS $$
DECLARE v_id bigint; v_lab bigint;
BEGIN
    SELECT laboratorio_id INTO STRICT v_lab FROM recurso WHERE id=p_recurso;
    PERFORM contexto_operacao(p_usuario);
    INSERT INTO reserva(laboratorio_id,usuario_id,recurso_principal_id,inicio,fim)
    VALUES(v_lab,p_usuario,p_recurso,p_inicio,p_fim) RETURNING id INTO v_id;
    RETURN v_id;
END $$;
CREATE FUNCTION cancelar_reserva(p_ator bigint,p_reserva bigint,p_motivo text) RETURNS void
LANGUAGE plpgsql SET search_path = gestao_lab, public AS $$
DECLARE v_lab bigint; v_usuario bigint;
BEGIN
    IF nullif(btrim(p_motivo),'') IS NULL THEN RAISE EXCEPTION 'Informe motivo de cancelamento' USING ERRCODE='23514'; END IF;
    SELECT laboratorio_id,usuario_id INTO STRICT v_lab,v_usuario FROM reserva WHERE id=p_reserva;
    PERFORM 1 FROM laboratorio WHERE id=v_lab FOR UPDATE;
    PERFORM contexto_operacao(p_ator,p_motivo);
    UPDATE reserva SET estado='CANCELADA',cancelado_em=clock_timestamp(),cancelado_por=p_ator,motivo_cancelamento=p_motivo
    WHERE id=p_reserva AND estado='CONFIRMADA';
    IF NOT FOUND THEN RAISE EXCEPTION 'Reserva não está confirmada' USING ERRCODE='23514'; END IF;
    PERFORM notificar(v_lab,v_usuario,'RESERVA_CANCELADA',p_motivo,jsonb_build_object('reserva_id',p_reserva));
    -- Não altera nem encerra empréstimos de chave.
END $$;

CREATE FUNCTION tg_guardar_local() RETURNS trigger
LANGUAGE plpgsql SET search_path = gestao_lab, public AS $$
DECLARE v_lab bigint; v_ids bigint[]; v_row jsonb; v_old jsonb;
BEGIN
    v_row:=to_jsonb(NEW); v_old:=to_jsonb(OLD);
    PERFORM exigir_isolamento();
    v_lab:=coalesce((v_row->>'laboratorio_id')::bigint,(v_old->>'laboratorio_id')::bigint);
    PERFORM 1 FROM laboratorio WHERE id=v_lab FOR UPDATE;
    IF TG_OP='UPDATE' AND (NEW.recurso_id,NEW.laboratorio_id) IS DISTINCT FROM (OLD.recurso_id,OLD.laboratorio_id) THEN
        RAISE EXCEPTION 'Identidade e laboratório de subtipo são imutáveis' USING ERRCODE='23514';
    END IF;
    IF TG_TABLE_NAME='equipamento' THEN
        IF TG_OP='UPDATE' AND (NEW.bancada_id,NEW.sala_direta_id,NEW.complemento_local)
           IS NOT DISTINCT FROM (OLD.bancada_id,OLD.sala_direta_id,OLD.complemento_local) THEN RETURN NEW; END IF;
        SELECT array_agg(DISTINCT id) INTO v_ids FROM (
            SELECT coalesce((v_row->>'recurso_id')::bigint,(v_old->>'recurso_id')::bigint) id
            UNION SELECT (v_row->>'bancada_id')::bigint UNION SELECT (v_old->>'bancada_id')::bigint
            UNION SELECT (v_row->>'sala_direta_id')::bigint UNION SELECT (v_old->>'sala_direta_id')::bigint
            UNION SELECT sala_id FROM bancada WHERE recurso_id IN ((v_row->>'bancada_id')::bigint,(v_old->>'bancada_id')::bigint)
        ) q;
    ELSIF TG_TABLE_NAME='bancada' THEN
        IF TG_OP='UPDATE' AND (NEW.sala_id,NEW.numero_identificacao) IS NOT DISTINCT FROM (OLD.sala_id,OLD.numero_identificacao) THEN RETURN NEW; END IF;
        SELECT array_agg(DISTINCT id) INTO v_ids FROM (
            SELECT coalesce((v_row->>'recurso_id')::bigint,(v_old->>'recurso_id')::bigint) id
            UNION SELECT (v_row->>'sala_id')::bigint UNION SELECT (v_old->>'sala_id')::bigint
            UNION SELECT recurso_id FROM equipamento WHERE bancada_id=coalesce((v_row->>'recurso_id')::bigint,(v_old->>'recurso_id')::bigint)
        ) q;
    ELSE
        IF TG_OP='UPDATE' AND (NEW.identificacao,NEW.localizacao,NEW.capacidade) IS NOT DISTINCT FROM (OLD.identificacao,OLD.localizacao,OLD.capacidade) THEN RETURN NEW; END IF;
        SELECT array_agg(recurso_id) INTO v_ids FROM recursos_abrangidos(coalesce((v_row->>'recurso_id')::bigint,(v_old->>'recurso_id')::bigint));
    END IF;
    IF EXISTS(SELECT 1 FROM reserva_recurso rr JOIN reserva r ON r.id=rr.reserva_id
              WHERE rr.recurso_id=ANY(v_ids) AND r.bloqueia AND r.fim>clock_timestamp()) THEN
