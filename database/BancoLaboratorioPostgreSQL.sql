CREATE FUNCTION tg_conferir_abrangencia() RETURNS trigger
LANGUAGE plpgsql SET search_path = gestao_lab, public AS $$
DECLARE v_id bigint; v_principal bigint; v_estado estado_reserva;
BEGIN
    v_id:=CASE WHEN TG_TABLE_NAME='reserva' THEN coalesce((to_jsonb(NEW)->>'id')::bigint,(to_jsonb(OLD)->>'id')::bigint)
               ELSE coalesce((to_jsonb(NEW)->>'reserva_id')::bigint,(to_jsonb(OLD)->>'reserva_id')::bigint) END;
    SELECT recurso_principal_id,estado INTO v_principal,v_estado FROM reserva WHERE id=v_id;
    -- Reserva histórica preserva composição original, mesmo após movimentações futuras.
    IF FOUND AND v_estado='CONFIRMADA' AND EXISTS(SELECT 1 FROM reserva WHERE id=v_id AND fim>clock_timestamp()) THEN
        IF EXISTS((SELECT recurso_id FROM recursos_abrangidos(v_principal) EXCEPT SELECT recurso_id FROM reserva_recurso WHERE reserva_id=v_id)
                  UNION ALL
                  (SELECT recurso_id FROM reserva_recurso WHERE reserva_id=v_id EXCEPT SELECT recurso_id FROM recursos_abrangidos(v_principal))) THEN
            RAISE EXCEPTION 'Abrangência incompleta ou divergente da reserva %',v_id USING ERRCODE='23514';
        END IF;
    END IF;
    RETURN NULL;
END $$;
