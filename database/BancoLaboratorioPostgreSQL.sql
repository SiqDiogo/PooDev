CREATE FUNCTION tg_validar_chave() RETURNS trigger
LANGUAGE plpgsql SET search_path = gestao_lab, public AS $$
BEGIN
    PERFORM exigir_isolamento();
    PERFORM 1 FROM laboratorio WHERE id=NEW.laboratorio_id FOR UPDATE;
    PERFORM exigir_gestor_chave(NEW.designada_por,coalesce(NEW.sala_id,NEW.bancada_id),NEW.laboratorio_id);
    IF TG_OP='UPDATE' THEN
        IF NEW.condicao IS DISTINCT FROM OLD.condicao AND pg_trigger_depth()<2 THEN
            RAISE EXCEPTION 'Condição de chave exige registro de ocorrência' USING ERRCODE='23514';
        END IF;
        IF (NEW.id,NEW.laboratorio_id) IS DISTINCT FROM (OLD.id,OLD.laboratorio_id) THEN
            RAISE EXCEPTION 'Identidade de cópia é imutável' USING ERRCODE='23514';
        END IF;
        IF EXISTS(SELECT 1 FROM emprestimo_chave WHERE chave_id=OLD.id AND devolucao_em IS NULL)
           AND (NEW.sala_id,NEW.bancada_id,NEW.designada_para,NEW.codigo_copia)
               IS DISTINCT FROM (OLD.sala_id,OLD.bancada_id,OLD.designada_para,OLD.codigo_copia) THEN
            RAISE EXCEPTION 'Não alterar designação de cópia emprestada' USING ERRCODE='23514';
        END IF;
        IF (NEW.sala_id,NEW.bancada_id) IS DISTINCT FROM (OLD.sala_id,OLD.bancada_id)
           AND EXISTS(SELECT 1 FROM emprestimo_chave WHERE chave_id=OLD.id) THEN
            RAISE EXCEPTION 'Destino de cópia com histórico é imutável; cadastre outra cópia' USING ERRCODE='23514';
        END IF;
    END IF;
    RETURN NEW;
END $$;
