CREATE FUNCTION tg_validar_protocolo() RETURNS trigger
LANGUAGE plpgsql SET search_path = gestao_lab, public AS $$
BEGIN
    PERFORM exigir_isolamento();
    PERFORM 1 FROM laboratorio WHERE id=NEW.laboratorio_id FOR UPDATE;
    IF TG_OP='INSERT' THEN
        PERFORM exigir_usuario(NEW.autor_id,NEW.laboratorio_id);
        IF NEW.assinado_em IS NOT NULL OR NEW.estado<>'NAO_VALIDADO' THEN
            RAISE EXCEPTION 'Protocolo inicia não validado e sem assinatura' USING ERRCODE='23514';
        END IF;
    ELSE
        IF (NEW.id,NEW.laboratorio_id,NEW.autor_id,NEW.criado_em) IS DISTINCT FROM (OLD.id,OLD.laboratorio_id,OLD.autor_id,OLD.criado_em) THEN
            RAISE EXCEPTION 'Identidade e autoria do protocolo são imutáveis' USING ERRCODE='23514';
        END IF;
        IF OLD.assinado_em IS NOT NULL AND (NEW.pdf_original,NEW.nome_arquivo,NEW.titulo,NEW.assinado_em,NEW.assinado_por)
            IS DISTINCT FROM (OLD.pdf_original,OLD.nome_arquivo,OLD.titulo,OLD.assinado_em,OLD.assinado_por) THEN
            RAISE EXCEPTION 'Protocolo assinado não pode mudar conteúdo ou assinatura' USING ERRCODE='23514';
        END IF;
        IF OLD.estado='VALIDADO' AND (NEW.estado,NEW.validado_em,NEW.validado_por) IS DISTINCT FROM (OLD.estado,OLD.validado_em,OLD.validado_por) THEN
            RAISE EXCEPTION 'Validação de protocolo é imutável' USING ERRCODE='23514';
        END IF;
    END IF;
    RETURN NEW;
END $$;
