CREATE VIEW vw_local_recurso AS
SELECT r.id recurso_id, r.laboratorio_id, l.nome laboratorio_nome, r.tipo, r.nome recurso_nome, r.estado,
       CASE r.tipo WHEN 'SALA' THEN r.id WHEN 'BANCADA' THEN b.sala_id ELSE coalesce(e.sala_direta_id, eb.sala_id) END sala_id,
       sr.nome sala_nome, s.identificacao sala_identificacao, s.localizacao sala_localizacao,
       CASE WHEN r.tipo='BANCADA' THEN r.id ELSE e.bancada_id END bancada_id,
       br.nome bancada_nome, coalesce(b.numero_identificacao,eb.numero_identificacao) bancada_identificacao,
       e.numero_patrimonio, e.complemento_local
FROM recurso r JOIN laboratorio l ON l.id=r.laboratorio_id
LEFT JOIN bancada b ON b.recurso_id=r.id
LEFT JOIN equipamento e ON e.recurso_id=r.id
LEFT JOIN bancada eb ON eb.recurso_id=e.bancada_id
LEFT JOIN sala s ON s.recurso_id=CASE r.tipo WHEN 'SALA' THEN r.id WHEN 'BANCADA' THEN b.sala_id ELSE coalesce(e.sala_direta_id,eb.sala_id) END
LEFT JOIN recurso sr ON sr.id=s.recurso_id
LEFT JOIN recurso br ON br.id=CASE WHEN r.tipo='BANCADA' THEN r.id ELSE e.bancada_id END;
CREATE VIEW vw_local_equipamento AS SELECT * FROM vw_local_recurso WHERE tipo='EQUIPAMENTO';
CREATE FUNCTION recursos_abrangidos(p_recurso bigint) RETURNS TABLE(recurso_id bigint)
LANGUAGE sql STABLE SET search_path = gestao_lab, public AS $$
    SELECT r.id FROM recurso r WHERE r.id=p_recurso
    UNION
    SELECT b.recurso_id FROM bancada b WHERE b.sala_id=p_recurso
    UNION
    SELECT e.recurso_id FROM equipamento e LEFT JOIN bancada b ON b.recurso_id=e.bancada_id
    WHERE e.bancada_id=p_recurso OR e.sala_direta_id=p_recurso OR b.sala_id=p_recurso
$$;
CREATE FUNCTION recursos_ancestrais(p_recurso bigint) RETURNS TABLE(recurso_id bigint)
LANGUAGE sql STABLE SET search_path = gestao_lab, public AS $$
    SELECT p_recurso
    UNION SELECT sala_id FROM vw_local_recurso WHERE recurso_id=p_recurso AND sala_id IS NOT NULL
    UNION SELECT bancada_id FROM vw_local_recurso WHERE recurso_id=p_recurso AND bancada_id IS NOT NULL
$$;
CREATE FUNCTION recurso_disponivel(p_recurso bigint, p_inicio timestamptz, p_fim timestamptz) RETURNS boolean
LANGUAGE sql STABLE SET search_path = gestao_lab, public AS $$
    SELECT p_inicio < p_fim
       AND EXISTS(SELECT 1 FROM recurso WHERE id=p_recurso)
       AND NOT EXISTS(SELECT 1 FROM recursos_abrangidos(p_recurso) a
                      CROSS JOIN LATERAL recursos_ancestrais(a.recurso_id) c JOIN recurso r ON r.id=c.recurso_id
                      WHERE r.estado<>'DISPONIVEL')
       AND NOT EXISTS(SELECT 1 FROM reserva_recurso rr JOIN recursos_abrangidos(p_recurso) a USING(recurso_id)
                      WHERE rr.bloqueia AND rr.periodo && tstzrange(p_inicio,p_fim,'[)'))
$$;

CREATE FUNCTION tg_validar_reserva() RETURNS trigger
LANGUAGE plpgsql SET search_path = gestao_lab, public AS $$
DECLARE v_lab laboratorio%ROWTYPE; v_pico integer;
BEGIN
    -- Um lock por laboratório mantém coerentes limites, composição e alterações concorrentes.
    PERFORM exigir_isolamento();
    SELECT * INTO STRICT v_lab FROM laboratorio WHERE id=NEW.laboratorio_id FOR UPDATE;
    IF TG_OP='UPDATE' THEN
        IF (NEW.id,NEW.laboratorio_id,NEW.usuario_id,NEW.recurso_principal_id,NEW.inicio,NEW.fim,NEW.criado_em)
           IS DISTINCT FROM (OLD.id,OLD.laboratorio_id,OLD.usuario_id,OLD.recurso_principal_id,OLD.inicio,OLD.fim,OLD.criado_em) THEN
            RAISE EXCEPTION 'Reserva imutável: cancelar e criar outra para alterar recurso ou período' USING ERRCODE='23514';
        END IF;
        IF OLD.estado<>'CONFIRMADA' AND NEW IS DISTINCT FROM OLD THEN
            RAISE EXCEPTION 'Reserva encerrada não pode ser alterada' USING ERRCODE='23514';
        END IF;
        IF NEW.estado='CANCELADA' AND OLD.estado='CONFIRMADA' THEN
            PERFORM exigir_usuario(NEW.cancelado_por,NEW.laboratorio_id);
            IF NEW.cancelado_por<>NEW.usuario_id AND NEW.cancelado_por<>v_lab.chefe_usuario_id THEN
                RAISE EXCEPTION 'Somente o dono ou Chefe pode cancelar' USING ERRCODE='42501';
            END IF;
        ELSIF NEW.estado='CONCLUIDA' AND clock_timestamp()<NEW.fim THEN
            RAISE EXCEPTION 'Conclusão somente após o fim da reserva' USING ERRCODE='23514';
        END IF;
        RETURN NEW;
    END IF;
    PERFORM exigir_usuario(NEW.usuario_id,NEW.laboratorio_id);
    IF NEW.estado<>'CONFIRMADA' THEN RAISE EXCEPTION 'Nova reserva deve ser CONFIRMADA' USING ERRCODE='23514'; END IF;
    IF NOT isfinite(NEW.inicio) OR NOT isfinite(NEW.fim) OR NEW.fim<=NEW.inicio THEN
        RAISE EXCEPTION 'Período inválido' USING ERRCODE='23514';
    END IF;
    IF NOT EXISTS(SELECT 1 FROM recurso WHERE id=NEW.recurso_principal_id AND laboratorio_id=NEW.laboratorio_id) THEN
        RAISE EXCEPTION 'Recurso de outro laboratório ou inexistente' USING ERRCODE='23503';
    END IF;
    IF v_lab.duracao_maxima_reserva IS NOT NULL AND NEW.fim-NEW.inicio>v_lab.duracao_maxima_reserva THEN
        RAISE EXCEPTION 'Duração excede o limite do laboratório' USING ERRCODE='23514';
    END IF;
    IF EXISTS(SELECT 1 FROM recursos_abrangidos(NEW.recurso_principal_id) a
              CROSS JOIN LATERAL recursos_ancestrais(a.recurso_id) c JOIN recurso r ON r.id=c.recurso_id
              WHERE r.estado<>'DISPONIVEL') THEN
        RAISE EXCEPTION 'Conjunto contém recurso ou local indisponível' USING ERRCODE='23514';
    END IF;
    IF EXISTS(SELECT 1 FROM proibicao_aluno_equipamento p JOIN recursos_abrangidos(NEW.recurso_principal_id) a ON a.recurso_id=p.equipamento_id
              WHERE p.aluno_id=NEW.usuario_id AND p.encerrada_em IS NULL) THEN
        RAISE EXCEPTION 'Aluno proibido de utilizar equipamento abrangido' USING ERRCODE='42501';
    END IF;
    IF v_lab.max_reservas_simultaneas IS NOT NULL THEN
        -- Pico real por usuário: não soma duas reservas consecutivas como simultâneas.
        WITH eventos AS (
            SELECT greatest(inicio,NEW.inicio) instante,1 delta FROM reserva
            WHERE usuario_id=NEW.usuario_id AND bloqueia AND periodo && tstzrange(NEW.inicio,NEW.fim,'[)')
            UNION ALL
            SELECT least(fim,NEW.fim),-1 FROM reserva
            WHERE usuario_id=NEW.usuario_id AND bloqueia AND periodo && tstzrange(NEW.inicio,NEW.fim,'[)')
        ), agrupados AS (SELECT instante,sum(delta) delta FROM eventos GROUP BY instante),
        acumulados AS (SELECT sum(delta) OVER(ORDER BY instante) qtd FROM agrupados)
        SELECT coalesce(max(qtd),0)::integer INTO v_pico FROM acumulados;
        IF v_pico+1>v_lab.max_reservas_simultaneas THEN
            RAISE EXCEPTION 'Quantidade simultânea excede o limite por usuário' USING ERRCODE='23514';
        END IF;
    END IF;
    RETURN NEW;
END $$;
CREATE TRIGGER validar_reserva BEFORE INSERT OR UPDATE ON reserva FOR EACH ROW EXECUTE FUNCTION tg_validar_reserva();
CREATE FUNCTION tg_materializar_abrangencia() RETURNS trigger
LANGUAGE plpgsql SET search_path = gestao_lab, public AS $$
