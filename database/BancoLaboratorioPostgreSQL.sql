CREATE FUNCTION tg_validar_proibicao() RETURNS trigger
LANGUAGE plpgsql SET search_path = gestao_lab, public AS $$
DECLARE v_reserva record;
BEGIN
    PERFORM exigir_isolamento();
    PERFORM 1 FROM laboratorio WHERE id=NEW.laboratorio_id FOR UPDATE;
    IF TG_OP='UPDATE' THEN
        IF (NEW.id,NEW.laboratorio_id,NEW.aluno_id,NEW.equipamento_id,NEW.motivo,NEW.aplicada_por,NEW.criada_em)
           IS DISTINCT FROM (OLD.id,OLD.laboratorio_id,OLD.aluno_id,OLD.equipamento_id,OLD.motivo,OLD.aplicada_por,OLD.criada_em)
           OR OLD.encerrada_em IS NOT NULL THEN
            RAISE EXCEPTION 'Proibição histórica é imutável' USING ERRCODE='23514';
        END IF;
        IF NEW.encerrada_em IS NOT NULL AND NOT EXISTS(SELECT 1 FROM solicitacao_reativacao
            WHERE proibicao_id=NEW.id AND estado='APROVADA' AND respondida_por=NEW.encerrada_por) THEN
            RAISE EXCEPTION 'Somente aprovação de reativação encerra a proibição' USING ERRCODE='23514';
        END IF;
    ELSE
        PERFORM exigir_chefe(NEW.aplicada_por,NEW.laboratorio_id);
        IF NEW.encerrada_em IS NOT NULL THEN RAISE EXCEPTION 'Nova proibição deve estar ativa' USING ERRCODE='23514'; END IF;
        PERFORM contexto_operacao(NEW.aplicada_por,NEW.motivo);
        FOR v_reserva IN SELECT r.id FROM reserva r JOIN reserva_recurso rr ON rr.reserva_id=r.id
            WHERE r.usuario_id=NEW.aluno_id AND r.bloqueia AND r.fim>clock_timestamp()
              AND rr.recurso_id=NEW.equipamento_id ORDER BY r.id LOOP
            PERFORM cancelar_reserva(NEW.aplicada_por,v_reserva.id,'Proibição de uso: '||NEW.motivo);
        END LOOP;
    END IF;
    RETURN NEW;
END $$;
