CREATE FUNCTION tg_estado_recurso() RETURNS trigger
LANGUAGE plpgsql SET search_path = gestao_lab, public AS $$
DECLARE v_reserva record; v_ator bigint; v_motivo text;
BEGIN
    PERFORM exigir_isolamento();
    PERFORM 1 FROM laboratorio WHERE id=NEW.laboratorio_id FOR UPDATE;
    IF (NEW.id,NEW.laboratorio_id,NEW.tipo) IS DISTINCT FROM (OLD.id,OLD.laboratorio_id,OLD.tipo) THEN
        RAISE EXCEPTION 'Identidade, laboratório e tipo de recurso são imutáveis' USING ERRCODE='23514';
    END IF;
    IF NEW.estado IS DISTINCT FROM OLD.estado THEN
        v_ator:=nullif(current_setting('app.usuario_id',true),'')::bigint;
        v_motivo:=nullif(current_setting('app.motivo',true),'');
        PERFORM exigir_chefe(v_ator,NEW.laboratorio_id);
        IF v_motivo IS NULL THEN RAISE EXCEPTION 'Mudança de estado exige motivo' USING ERRCODE='23514'; END IF;
        IF NEW.estado<>'DISPONIVEL' THEN
            FOR v_reserva IN SELECT DISTINCT r.id FROM reserva r JOIN reserva_recurso rr ON rr.reserva_id=r.id
                JOIN recursos_abrangidos(NEW.id) a ON a.recurso_id=rr.recurso_id
                WHERE r.bloqueia AND r.fim>clock_timestamp() ORDER BY r.id LOOP
                PERFORM cancelar_reserva(v_ator,v_reserva.id,'Recurso indisponível: '||v_motivo);
            END LOOP;
        END IF;
    END IF;
    RETURN NEW;
END $$;
