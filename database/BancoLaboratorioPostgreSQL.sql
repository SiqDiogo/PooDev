CREATE FUNCTION tg_validar_emprestimo() RETURNS trigger
LANGUAGE plpgsql SET search_path = gestao_lab, public AS $$
DECLARE v_chave chave%ROWTYPE; v_reserva reserva%ROWTYPE;
BEGIN
    PERFORM exigir_isolamento();
    PERFORM 1 FROM laboratorio WHERE id=NEW.laboratorio_id FOR UPDATE;
    SELECT * INTO STRICT v_chave FROM chave WHERE id=NEW.chave_id FOR UPDATE;
    IF TG_OP='UPDATE' THEN
        IF (NEW.id,NEW.laboratorio_id,NEW.chave_id,NEW.usuario_id,NEW.reserva_id,NEW.retirada_em,NEW.entregue_por)
           IS DISTINCT FROM (OLD.id,OLD.laboratorio_id,OLD.chave_id,OLD.usuario_id,OLD.reserva_id,OLD.retirada_em,OLD.entregue_por)
           OR OLD.devolucao_em IS NOT NULL THEN
            RAISE EXCEPTION 'Empréstimo histórico é imutável; somente devolução do aberto é permitida' USING ERRCODE='23514';
        END IF;
        IF NEW.devolucao_em IS NULL THEN RAISE EXCEPTION 'Atualização exige devolução física' USING ERRCODE='23514'; END IF;
        PERFORM exigir_gestor_chave(NEW.recebido_por,coalesce(v_chave.sala_id,v_chave.bancada_id),NEW.laboratorio_id);
        RETURN NEW;
    END IF;
    IF NEW.devolucao_em IS NOT NULL THEN RAISE EXCEPTION 'Novo empréstimo deve permanecer aberto' USING ERRCODE='23514'; END IF;
    PERFORM exigir_usuario(NEW.usuario_id,NEW.laboratorio_id);
    PERFORM exigir_gestor_chave(NEW.entregue_por,coalesce(v_chave.sala_id,v_chave.bancada_id),NEW.laboratorio_id);
    SELECT * INTO STRICT v_reserva FROM reserva WHERE id=NEW.reserva_id;
    IF v_reserva.usuario_id<>NEW.usuario_id OR v_reserva.laboratorio_id<>NEW.laboratorio_id
       OR v_reserva.estado<>'CONFIRMADA' OR v_reserva.fim<=clock_timestamp() OR NEW.retirada_em>=v_reserva.fim THEN
        RAISE EXCEPTION 'Reserva não autoriza a retirada para este usuário' USING ERRCODE='42501';
    END IF;
    IF v_chave.condicao<>'OPERACIONAL' THEN RAISE EXCEPTION 'Cópia indisponível ou extraviada' USING ERRCODE='23514'; END IF;
    IF v_chave.designada_para IS NOT NULL AND v_chave.designada_para<>NEW.usuario_id THEN
        RAISE EXCEPTION 'Cópia designada a outro usuário' USING ERRCODE='42501';
    END IF;
    IF NOT EXISTS(SELECT 1 FROM reserva_recurso rr CROSS JOIN LATERAL recursos_ancestrais(rr.recurso_id) a
                  WHERE rr.reserva_id=NEW.reserva_id AND a.recurso_id=coalesce(v_chave.sala_id,v_chave.bancada_id)) THEN
        RAISE EXCEPTION 'Chave não corresponde ao acesso da reserva' USING ERRCODE='42501';
    END IF;
    RETURN NEW;
END $$;
