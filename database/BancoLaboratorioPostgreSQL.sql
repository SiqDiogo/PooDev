CREATE FUNCTION tg_recurso_subtipo() RETURNS trigger
LANGUAGE plpgsql SET search_path = gestao_lab, public AS $$
DECLARE v_id bigint; v_tipo tipo_recurso; v_ok boolean;
BEGIN
    v_id := CASE WHEN TG_TABLE_NAME='recurso' THEN coalesce((to_jsonb(NEW)->>'id')::bigint,(to_jsonb(OLD)->>'id')::bigint)
                 ELSE coalesce((to_jsonb(NEW)->>'recurso_id')::bigint,(to_jsonb(OLD)->>'recurso_id')::bigint) END;
    SELECT tipo INTO v_tipo FROM recurso WHERE id=v_id;
    IF FOUND THEN
        v_ok := CASE v_tipo WHEN 'SALA' THEN EXISTS(SELECT 1 FROM sala WHERE recurso_id=v_id)
                  WHEN 'BANCADA' THEN EXISTS(SELECT 1 FROM bancada WHERE recurso_id=v_id)
                  ELSE EXISTS(SELECT 1 FROM equipamento WHERE recurso_id=v_id) END;
        IF NOT v_ok THEN RAISE EXCEPTION 'Recurso % sem subclasse % correspondente',v_id,v_tipo USING ERRCODE='23514'; END IF;
    END IF;
    RETURN NULL;
END $$;
